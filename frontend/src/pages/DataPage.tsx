import { useState } from "react";
import { api } from "../api";
import { ErrorBox, useAsync } from "../components/ui";
import { useMeta } from "../meta";

export function DataPage() {
  const meta = useMeta();
  const [mode, setMode] = useState<"append" | "replace">("append");
  const [message, setMessage] = useState<string | null>(null);
  const { busy, error, run } = useAsync();

  const onFile = (file: File | undefined) => {
    if (!file) return;
    const kind = file.name.toLowerCase().endsWith(".json") ? "json" : "csv";
    if (mode === "replace" && !confirm("Replace ALL current applications with this file?")) return;
    setMessage(null);
    run(async () => {
      const res = await api.importFile(kind, await file.text(), mode);
      setMessage(`Imported ${res.imported} application(s).`);
    });
  };

  return (
    <div className="data-page">
      <section className="card">
        <h2>Your data stays on this computer</h2>
        <ul className="plain">
          <li>
            Everything is stored in <code>data/{meta.db_file}</code>, a local SQLite file. The <code>data/</code>{" "}
            folder is git-ignored, and the pre-commit hook refuses to commit databases, exports or backups.
          </li>
          <li>The server only listens on 127.0.0.1 and makes no external requests: no analytics, no telemetry.</li>
          <li>
            To keep the database somewhere else (for example an encrypted or synced folder), set{" "}
            <code>APPLYTRAIL_DB=/path/to/file.db</code>.
          </li>
          {meta.demo && (
            <li>
              <strong>You are in demo mode.</strong> The data is fictional and generated by <code>make seed</code>.
            </li>
          )}
        </ul>
      </section>

      <div className="grid-cards">
        <section className="card">
          <h2>Export</h2>
          <p className="muted small">
            Downloaded files contain your personal data. Keep them out of the repository.
          </p>
          <div className="row gap-s">
            <a className="btn" href="/api/export/json" download>
              Full backup (.json)
            </a>
            <a className="btn" href="/api/export/csv" download>
              Spreadsheet (.csv)
            </a>
          </div>
        </section>

        <section className="card">
          <h2>Import</h2>
          <p className="muted small">
            A JSON backup from this app, or a CSV with at least <code>company</code>, <code>role</code> and{" "}
            <code>applied_date</code> (YYYY-MM-DD) columns. Optional columns: any exported column, e.g.{" "}
            <code>source</code>, <code>outcome</code>, <code>current_stage</code>, <code>screen_date</code>. Imports
            are all-or-nothing: if any row is invalid, nothing is imported.
          </p>
          <div className="row gap-s wrap">
            <div className="segmented">
              <button className={mode === "append" ? "on" : ""} onClick={() => setMode("append")}>
                Add to existing
              </button>
              <button className={mode === "replace" ? "on" : ""} onClick={() => setMode("replace")}>
                Replace everything
              </button>
            </div>
            <label className="btn">
              {busy ? "Importing…" : "Choose file…"}
              <input
                type="file"
                accept=".json,.csv,text/csv,application/json"
                hidden
                onChange={(e) => {
                  onFile(e.target.files?.[0]);
                  e.target.value = "";
                }}
              />
            </label>
          </div>
          {message && <p className="success">{message}</p>}
          <ErrorBox error={error} />
        </section>
      </div>
    </div>
  );
}
